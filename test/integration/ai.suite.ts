/** AI assistance with a fake provider: proposals become proposed cells, explanations open beside. */
import { strict as assert } from 'node:assert';
import * as vscode from 'vscode';
import { LANG, Test, closeAll, openRunbook, read, setConfig, step, writeFile } from './suite';

export const tests: Test[] = [];
const test = (name: string, fn: () => Promise<void>): void => void tests.push({ name, fn });

const SAMPLE =
  `# Incident\n\n\`\`\`${LANG}\necho hi\n\`\`\`\n` +
  '<!-- md-runbook:output start exit=0 ran=2026-10-18T14:20:00+02:00 -->\n```text\nhi\n```\n<!-- md-runbook:output end -->\n\nNotes.\n';

async function withFake(answer: string, fn: () => Promise<void>): Promise<void> {
  await vscode.commands.executeCommand('mdRunbook._ai.useFakeProvider', answer);
  await setConfig('ai.confirmBeforeSend', false);
  try {
    await fn();
  } finally {
    await vscode.commands.executeCommand('mdRunbook._ai.useFakeProvider', undefined);
    await setConfig('ai.confirmBeforeSend', undefined);
  }
}

test('AI: Suggest Next Steps inserts proposed cells that are saved with their fence info', async () => {
  const answer = 'List the pods first.\n\n```bash proposed by=ai reason="list pods"\nkubectl get pods\n```\n\n```json\n{}\n```\n';
  await withFake(answer, async () => {
    const uri = writeFile('ai-suggest.md', SAMPLE);
    const nb = (await openRunbook(uri)).notebook;
    const n = await step('suggest', vscode.commands.executeCommand<number>('mdRunbook.ai.suggestNextSteps', nb.cellAt(1)));
    assert.equal(n, 1);
    assert.equal(nb.cellAt(2).kind, vscode.NotebookCellKind.Code);
    assert.equal(nb.cellAt(2).document.getText(), 'kubectl get pods');
    assert.equal(nb.cellAt(2).outputs.length, 0, 'nothing is run');
    assert.ok(await step('save', nb.save()));
    const saved = read(uri);
    assert.match(saved, /```bash proposed by=ai reason="list pods"\nkubectl get pods\n```\n/);
    assert.match(saved, /<!-- md-runbook:output end -->\n\n```bash proposed/);
    assert.match(saved, /```\n\nNotes\.\n$/);
  });
  await closeAll();
});

test('AI: Explain Output opens the answer beside without touching the runbook', async () => {
  await withFake('The output **hi** means the shell works.', async () => {
    const uri = writeFile('ai-explain.md', SAMPLE);
    const nb = (await openRunbook(uri)).notebook;
    const out = await step('explain', vscode.commands.executeCommand<vscode.Uri>('mdRunbook.ai.explainOutput', nb.cellAt(1)));
    assert.ok(out, 'no document returned');
    const doc = vscode.workspace.textDocuments.find((d) => d.uri.toString() === out.toString());
    assert.ok(doc, 'explanation document not open');
    assert.match(doc.getText(), /The output \*\*hi\*\* means the shell works\./);
    assert.equal(nb.cellCount, 3, 'runbook unchanged');
    assert.equal(nb.isDirty, false);
    await vscode.window.showTextDocument(doc);
    await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
  });
  await closeAll();
});

test('AI: Summarize Incident inserts, then updates, one findings draft cell', async () => {
  const uri = writeFile('ai-summary.md', SAMPLE);
  const nb = (await openRunbook(uri)).notebook;
  await withFake('### Summary\nFirst draft.', async () => {
    assert.equal(await step('summarize', vscode.commands.executeCommand<boolean>('mdRunbook.ai.summarizeIncident')), true);
  });
  await withFake('### Summary\nSecond draft.', async () => {
    assert.equal(await step('summarize again', vscode.commands.executeCommand<boolean>('mdRunbook.ai.summarizeIncident')), true);
  });
  const findings = nb.getCells().filter((c) => c.document.getText().startsWith('## Findings (AI draft)'));
  assert.equal(findings.length, 1);
  assert.match(findings[0]!.document.getText(), /Second draft\./);
  assert.ok(await step('save', nb.save()));
  assert.match(read(uri), /Notes\.\n\n## Findings \(AI draft\)\n\n> Draft generated by/);
  await closeAll();
});
